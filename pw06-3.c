#include <stdio.h>


int main()
{
    int a;
    int k=0;
    int s=0;
    double sr=0;
    while (scanf("%d", &a) == 1 && a != 0)
    {
        if((a%10)!=(a/10) && 10<=a && a<=99)
        {
            k++;
            s=s+a;
        }



    }
    if (k > 0)
    {
        sr=(double)s/(double)k;
    }
    printf("Количество двузначных чисел с разными цифрами: %d\n", k);
    printf("Среднее арифметическое: %f\n", sr);
}
/*
Операторы && и || вычисляются слева направо.
Для &&: если левая часть ложна, правая не вычисляется.
Для ||: если левая часть истинна, правая не вычисляется.
*/